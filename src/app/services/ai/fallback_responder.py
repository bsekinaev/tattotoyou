from app.core.logging import get_logger

logger = get_logger(__name__)


class FallbackResponder:
    """Консервативные ответы без неподтверждённых фактов студии."""

    TEMPLATES = {
        "pricing": "Сейчас не могу надёжно подтвердить стоимость. Передам вопрос Соне, и она уточнит цену после деталей эскиза 💛",
        "booking": "Сейчас не могу надёжно подтвердить свободное время. Передам вопрос Соне, и она поможет с записью 💛",
        "aftercare": "Не хочу дать неточную рекомендацию по уходу. Передам вопрос Соне, чтобы она ответила по вашей ситуации 💛",
        "portfolio": "Уточню у Сони подходящие примеры работ и вернусь с точным ответом 💛",
        "health": "Это важный вопрос о здоровье. Я передам его мастеру, чтобы она ответила безопасно и по вашей ситуации 💛",
        "complaint": "Мне очень жаль, что так вышло. Я передала диалог Соне, и она лично разберётся в ситуации 🙏",
        "ambiguous": "Сейчас не могу ответить надёжно, поэтому передам вопрос Соне. Она скоро подключится к диалогу 💛",
    }

    @classmethod
    def get_response(cls, intent: str) -> str:
        logger.warning("fallback_response_used", intent=intent)
        return cls.TEMPLATES.get(intent, cls.TEMPLATES["ambiguous"])
